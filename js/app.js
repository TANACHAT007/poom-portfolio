// ---------------------------------------------------------------
//  Offline outbox
// ---------------------------------------------------------------
// The Realtime Database web SDK queues writes only in memory (lost on reload) and, while offline,
// `await set(...)` never settles instead of rejecting. So: build the key on the client (push()
// needs no network), try the write with a timeout, and on failure persist the record to
// localStorage and replay it later. Retries target the exact same path, so replaying a write
// that did land just rewrites identical data — no duplicate rows.
const OUTBOX_KEY = "poom-portfolio-outbox";
const WRITE_TIMEOUT_MS = 8000;
const OUTBOX_MAX_AGE_MS = 7 * 24 * 60 * 60 * 1000; // a week-old record is no longer worth replaying
const OUTBOX_MAX_ITEMS = 50;

const outboxRead = () => {
  try { return JSON.parse(localStorage.getItem(OUTBOX_KEY) || "[]"); } catch (e) { return []; }
};
const outboxWrite = (items) => {
  try { localStorage.setItem(OUTBOX_KEY, JSON.stringify(items.slice(-OUTBOX_MAX_ITEMS))); } catch (e) {}
};

/** Number of writes still waiting to reach the server, for this user. */
export function outboxCount(uid) {
  const now = Date.now();
  return outboxRead().filter((i) => i.uid === uid && now - i.queuedAt < OUTBOX_MAX_AGE_MS).length;
}

/**
 * Write `data` to `path`, or keep it safe on this device until the connection comes back.
 * Returns "saved" (reached the server) or "queued" (waiting locally).
 * serverTimestamp() cannot survive localStorage, so pass `at: "SERVER_TIME"`: it becomes the real
 * sentinel when sent live, or the device clock plus `queuedOffline: true` when queued.
 */
export async function saveOrQueue(path, data, uid) {
  const send = (payload, offline) => {
    const body = { ...payload };
    if (body.at === "SERVER_TIME") body.at = offline ? Date.now() : serverTimestamp();
    if (offline) body.queuedOffline = true;
    return body;
  };

  if (navigator.onLine) {
    try {
      const ok = await Promise.race([
        set(ref(db, path), send(data, false)).then(() => true),
        new Promise((r) => setTimeout(() => r(false), WRITE_TIMEOUT_MS)),
      ]);
      if (ok) return "saved";
    } catch (e) {
      console.warn("saveOrQueue: write failed, falling back to outbox", path, e);
    }
  }
  const items = outboxRead();
  items.push({ path, data: send(data, true), uid, queuedAt: Date.now() });
  outboxWrite(items);
  return "queued";
}

/** Replay everything queued for this user. Safe to call as often as you like. */
export async function flushOutbox(uid) {
  if (!navigator.onLine) return { sent: 0, left: outboxCount(uid) };
  const now = Date.now();
  const all = outboxRead();
  const mine = all.filter((i) => i.uid === uid && now - i.queuedAt < OUTBOX_MAX_AGE_MS);
  const others = all.filter((i) => i.uid !== uid && now - i.queuedAt < OUTBOX_MAX_AGE_MS);
  let sent = 0;
  const stillPending = [];
  for (const item of mine) {
    try {
      const ok = await Promise.race([
        set(ref(db, item.path), item.data).then(() => true),
        new Promise((r) => setTimeout(() => r(false), WRITE_TIMEOUT_MS)),
      ]);
      if (ok) sent++; else stillPending.push(item);
    } catch (e) {
      // a rules rejection will never succeed on retry — drop it rather than loop forever
      if (String(e?.code || e?.message || "").includes("PERMISSION_DENIED")) {
        console.warn("outbox: permission denied, discarding", item.path, e);
      } else stillPending.push(item);
    }
  }
  outboxWrite([...others, ...stillPending]);
  if (sent) toast(`ส่งข้อมูลที่ค้างไว้แล้ว ${sent} รายการ`, "success");
  return { sent, left: stillPending.length };
}

/** Wire automatic replay: on sign-in, on reconnect, and when the tab is shown again. */
export function initOutbox(uid) {
  if (!uid || window.__outboxWired === uid) return;
  window.__outboxWired = uid;
  const run = () => flushOutbox(uid).then(() => renderOutboxBadge(uid)).catch(() => {});
  window.addEventListener("online", run);
  document.addEventListener("visibilitychange", () => { if (!document.hidden) run(); });
  run();
}

