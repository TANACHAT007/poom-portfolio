// A chart without labels is decoration, not data: both take optional labels / legend / units and
// expose a text summary to screen readers.
export function lineChart(values, opts = {}) {
  const { w = 320, h = 96, color = BRAND[500], max = Math.max(1, ...values), min = 0, labels = [], yLabel = "", xLabel = "", legend = "", unit = "" } = opts;
  if (!values.length) return `<div class="text-sm text-slate-400 py-6 text-center">ยังไม่มีข้อมูล</div>`;
  const pad = 8, n = values.length;
  const X = (i) => (n <= 1 ? w / 2 : pad + (i * (w - 2 * pad)) / (n - 1));
  const Y = (v) => h - pad - ((v - min) / ((max - min) || 1)) * (h - 2 * pad);
  const line = values.map((v, i) => `${X(i).toFixed(1)},${Y(v).toFixed(1)}`).join(" ");
  const area = `${pad},${h - pad} ${line} ${(w - pad).toFixed(1)},${h - pad}`;
  const dots = values.map((v, i) => `<circle cx="${X(i).toFixed(1)}" cy="${Y(v).toFixed(1)}" r="2.6" fill="${color}"/>`).join("");
  const mid = (min + max) / 2;
  const guides = [max, mid, min].map((v) => `<line x1="${pad}" y1="${Y(v).toFixed(1)}" x2="${w - pad}" y2="${Y(v).toFixed(1)}" stroke="#94a3b8" stroke-opacity=".35" stroke-width="1" stroke-dasharray="3 3"/>`).join("");
  const first = labels[0] || "", last = labels[labels.length - 1] || "";
  const summary = `${legend || "data"}: ${values.length} points ${first} – ${last}, min ${Math.min(...values)}${unit}, max ${Math.max(...values)}${unit}, latest ${values[values.length - 1]}${unit}`;
  return `<figure class="m-0">
    ${legend ? `<figcaption class="flex items-center gap-1.5 text-[11px] text-slate-500 mb-1.5"><span class="w-2.5 h-2.5 rounded-full" style="background:${color}"></span>${escapeHtml(legend)}</figcaption>` : ""}
    <div class="flex gap-1.5">
      ${yLabel ? `<div class="flex flex-col justify-between text-[9px] text-slate-400 shrink-0 py-0.5"><span>${escapeHtml(String(max))}</span><span>${escapeHtml(String(mid))}</span><span>${escapeHtml(String(min))}</span></div>` : ""}
      <svg viewBox="0 0 ${w} ${h}" preserveAspectRatio="none" class="w-full" style="height:${h}px" role="img" aria-label="${escapeHtml(summary)}">
        ${guides}
        <polyline points="${area}" fill="${color}" fill-opacity="0.12" stroke="none"/>
        <polyline points="${line}" fill="none" stroke="${color}" stroke-width="2" stroke-linejoin="round"/>${dots}
      </svg>
    </div>
    ${labels.length ? `<div class="flex justify-between text-[9px] text-slate-400 mt-1 ${yLabel ? "pl-6" : ""}"><span>${escapeHtml(first)}</span>${labels.length > 2 ? `<span>${escapeHtml(labels[Math.floor(labels.length / 2)])}</span>` : ""}<span>${escapeHtml(last)}</span></div>` : ""}
    ${(yLabel || xLabel) ? `<div class="flex justify-between text-[10px] text-slate-400 mt-1"><span>${escapeHtml(yLabel)}</span><span>${escapeHtml(xLabel)}</span></div>` : ""}
  </figure>`;
}
