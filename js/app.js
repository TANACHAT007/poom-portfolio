// ---------- Modal accessibility (focus trap) ----------
// Every dialog in this app is a `fixed inset-0` overlay shown by removing `hidden`. This wires
// role=dialog, aria-modal, a name from its heading, focus-in on open, Tab trapping and focus
// return on close — centrally, for every such overlay, including ones created later.
function initModalA11y() {
  if (window.__modalA11yWired) return;
  window.__modalA11yWired = true;

  const FOCUSABLE = "a[href], area[href], button, input, select, textarea, [tabindex]";
  const isVisible = (el) => !!(el.offsetWidth || el.offsetHeight || el.getClientRects().length);
  const focusables = (root) => [...root.querySelectorAll(FOCUSABLE)].filter((el) => !el.disabled && el.tabIndex !== -1 && !el.hasAttribute("hidden") && isVisible(el));
  const isOpen = (el) => el instanceof HTMLElement && !el.classList.contains("hidden") && /(^|\s)fixed(\s|$)/.test(el.className) && /(^|\s)inset-0(\s|$)/.test(el.className) && !el.hasAttribute("data-no-modal");
  const openModals = () => [...document.querySelectorAll('[class*="fixed"][class*="inset-0"]')].filter(isOpen)
    .sort((a, b) => (parseInt(getComputedStyle(a).zIndex) || 0) - (parseInt(getComputedStyle(b).zIndex) || 0));
  const topModal = () => openModals().pop() || null;

  let seq = 0;
  const markOpen = (modal) => {
    if (modal.dataset.a11yOpen === "1") return;
    modal.dataset.a11yOpen = "1";
    if (!modal.getAttribute("role")) modal.setAttribute("role", "dialog");
    modal.setAttribute("aria-modal", "true");
    if (!modal.getAttribute("aria-labelledby")) {
      const h = modal.querySelector("h1, h2, h3, h4");
      if (h) { if (!h.id) h.id = `modal-title-${++seq}`; modal.setAttribute("aria-labelledby", h.id); }
    }
    modal.__returnFocus = document.activeElement;
    const f = focusables(modal);
    if (f.length) f[0].focus(); else { modal.tabIndex = -1; modal.focus(); }
  };
  const markClosed = (modal) => {
    if (modal.dataset.a11yOpen !== "1") return;
    delete modal.dataset.a11yOpen;
    modal.removeAttribute("aria-modal");
    const back = modal.__returnFocus;
    modal.__returnFocus = null;
    if (back && document.contains(back) && isVisible(back)) { try { back.focus(); } catch (e) {} }
  };
  let queued = false;
  const sync = () => {
    queued = false;
    document.querySelectorAll('[class*="fixed"][class*="inset-0"]').forEach((el) => { if (isOpen(el)) markOpen(el); else markClosed(el); });
  };
  const scheduleSync = () => { if (!queued) { queued = true; requestAnimationFrame(sync); } };
  new MutationObserver(scheduleSync).observe(document.documentElement, { attributes: true, attributeFilter: ["class"], subtree: true, childList: true });
  sync();

  document.addEventListener("keydown", (e) => {
    if (e.key !== "Tab") return;
    const modal = topModal(); if (!modal) return;
    const f = focusables(modal);
    if (!f.length) { e.preventDefault(); return; }
    const first = f[0], last = f[f.length - 1];
    const outside = !modal.contains(document.activeElement);
    if (e.shiftKey && (outside || document.activeElement === first)) { e.preventDefault(); last.focus(); }
    else if (!e.shiftKey && (outside || document.activeElement === last)) { e.preventDefault(); first.focus(); }
  });
  document.addEventListener("focusin", (e) => {
    const modal = topModal(); if (!modal || modal.contains(e.target)) return;
    const f = focusables(modal);
    (f[0] || modal).focus();
  });
}

// ---------- Modal dismissal (Esc + backdrop tap) ----------
// Esc always closes the top modal; a backdrop tap closes it only if nothing was typed into it
// (a stray tap must not discard a half-filled form). Closing clicks the modal's OWN close control
// ([data-modal-close], [id$="-close"], .ic-cancel) so it can release what it owns (camera,
// pending promise, "seen" flag); only if it has none is `hidden` added directly.
function initModalDismiss() {
  if (window.__modalDismissWired) return;
  window.__modalDismissWired = true;
  const isOpenModal = (el) => el instanceof HTMLElement && !el.classList.contains("hidden") && /(^|\s)fixed(\s|$)/.test(el.className) && /(^|\s)inset-0(\s|$)/.test(el.className) && !el.hasAttribute("data-no-modal");
  const openModals = () => [...document.querySelectorAll('[class*="fixed"][class*="inset-0"]')].filter(isOpenModal)
    .sort((a, b) => (parseInt(getComputedStyle(a).zIndex) || 0) - (parseInt(getComputedStyle(b).zIndex) || 0));

  document.addEventListener("input", (e) => {
    const modal = e.target instanceof HTMLElement ? e.target.closest('[class*="fixed"][class*="inset-0"]') : null;
    if (modal) modal.dataset.userEdited = "1";
  }, true);
  new MutationObserver((muts) => {
    for (const m of muts) {
      const el = m.target;
      if (el instanceof HTMLElement && el.classList.contains("hidden") && el.dataset.userEdited) delete el.dataset.userEdited;
    }
  }).observe(document.documentElement, { attributes: true, attributeFilter: ["class"], subtree: true });

  const dismissModal = (modal) => {
    const own = modal.querySelector('[data-modal-close], [id$="-close"], .ic-cancel');
    if (own) { own.click(); return; }
    modal.classList.add("hidden");
  };
  document.addEventListener("keydown", (e) => {
    if (e.key !== "Escape") return;
    const top = openModals().pop();
    if (top) dismissModal(top);
  });
  document.addEventListener("click", (e) => {
    const modal = e.target;
    if (!isOpenModal(modal) || modal.dataset.userEdited === "1") return;
    dismissModal(modal);
  });
}

