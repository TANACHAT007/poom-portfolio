// Sign-up is two steps (create Auth account, then write users/$uid). If the second step fails
// (connection drops at the wrong moment) the account exists with no profile, and "sign up again"
// can never succeed (email-already-in-use). We heal that on the next sign-in using details stashed
// at sign-up time — but only when there is evidence of an interrupted sign-up, so an account whose
// profile an admin deliberately removed is not silently resurrected.
const PENDING_PROFILE_KEY = "poom-portfolio-pending-profile";
export function stashPendingProfile(p) {
  try { localStorage.setItem(PENDING_PROFILE_KEY, JSON.stringify(p)); } catch (e) {}
}
export function clearPendingProfile() {
  try { localStorage.removeItem(PENDING_PROFILE_KEY); } catch (e) {}
}
async function healMissingProfile(user) {
  let pending = null;
  try {
    const raw = localStorage.getItem(PENDING_PROFILE_KEY);
    if (raw) { const p = JSON.parse(raw); if (p && p.uid === user.uid) pending = p; }
  } catch (e) {}
  const createdAt = Date.parse(user.metadata?.creationTime || "");
  const freshSignup = Number.isFinite(createdAt) && Date.now() - createdAt < 15 * 60 * 1000;
  if (!pending && !freshSignup) return null;
  const profile = {
    name: String(pending?.name || user.displayName || (user.email || "").split("@")[0] || "ผู้ใช้").slice(0, 80),
    email: user.email || pending?.email || "",
    role: "user", // never self-grant a higher role
    photo: user.photoURL || "",
    createdAt: Date.now(),
    recovered: true, // marker so the repair is visible if anyone audits the data later
  };
  try {
    await set(ref(db, p(`users/${user.uid}`)), profile);
    clearPendingProfile();
    return profile;
  } catch (e) {
    console.error("[poom-portfolio] profile recovery failed:", e);
    return null;
  }
}

// ---------- Auth guard ----------
// usage: const { user, profile } = await requireAuth({ roles: ["admin"] })
// Redirects to auth.html when signed out, or to dashboard.html when the role does not match.
export function requireAuth(opts = {}) {
  const { roles = null, redirect = "auth.html" } = opts;
  return new Promise((resolve) => {
    const stop = onAuthStateChanged(auth, async (user) => {
      stop();
      if (!user) { window.location.href = redirect; return; }
      let profile = null;
      try { profile = await getProfile(user.uid); } catch (e) { console.warn("profile read failed", e); }
      if (!profile) profile = await healMissingProfile(user);
      if (roles && (!profile || !roles.includes(profile.role))) {
        toast("คุณไม่มีสิทธิ์เข้าถึงหน้านี้", "error");
        setTimeout(() => (window.location.href = "dashboard.html"), 1200);
        return;
      }
      try { initOutbox(user.uid); } catch (e) { console.error("outbox init failed", e); }
      try { initErrorLogging(user.uid); } catch (e) { console.error("error logging init failed", e); }
      resolve({ user, profile });
    });
  });
}

// Resolve the current auth state without redirecting.
let _sessionPromise = null;
export function currentUser() {
  if (_sessionPromise) return _sessionPromise;
  _sessionPromise = new Promise((resolve) => {
    const stop = onAuthStateChanged(auth, async (user) => {
      stop();
      if (!user) return resolve(null);
      let profile = null;
      try { profile = await getProfile(user.uid); } catch (e) {}
      if (!profile) profile = await healMissingProfile(user);
      resolve({ user, profile });
    });
  });
  return _sessionPromise;
}

